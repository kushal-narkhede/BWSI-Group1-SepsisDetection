class PositionalEncoding(nn.Module):
    def __init__(self, d_model, max_len=500, dropout=0.1):
        super().__init__()
        self.dropout = nn.Dropout(p=dropout)
        pe = torch.zeros(max_len, d_model)
        position = torch.arange(0, max_len, dtype=torch.float).unsqueeze(1)
        div_term = torch.exp(torch.arange(0, d_model, 2).float() * (-np.log(10000.0) / d_model))
        pe[:, 0::2] = torch.sin(position * div_term)
        pe[:, 1::2] = torch.cos(position * div_term)
        pe = pe.unsqueeze(0)
        self.register_buffer('pe', pe)

    def forward(self, x):
        x = x + self.pe[:, :x.size(1)]
        return self.dropout(x)

class TemporalTransformer(nn.Module):
    def __init__(self, num_features, d_model=64, nhead=4, num_layers=2, dim_feedforward=128, dropout=0.2, max_len=48):
        super().__init__()
        self.input_projection = nn.Linear(num_features, d_model)
        self.pos_encoder = PositionalEncoding(d_model, max_len=max_len, dropout=dropout)
        encoder_layer = nn.TransformerEncoderLayer(
            d_model=d_model, nhead=nhead, dim_feedforward=dim_feedforward, dropout=dropout, batch_first=True
        )
        self.transformer_encoder = nn.TransformerEncoder(encoder_layer, num_layers=num_layers)
        self.classifier = nn.Sequential(
            nn.Linear(d_model, 32), nn.ReLU(), nn.Dropout(dropout), nn.Linear(32, 1)
        )

    def forward(self, x, src_key_padding_mask=None):
        x = self.input_projection(x)
        x = self.pos_encoder(x)
        x = self.transformer_encoder(x, src_key_padding_mask=src_key_padding_mask)
        return self.classifier(x).squeeze(-1)

def evaluate(model, loader, dev):
    model.eval()
    all_probs, all_targets = [], []
    with torch.no_grad():
        for bx, by, bmask in loader:
            bx, bmask = bx.to(dev), bmask.to(dev)
            logits = model(bx, src_key_padding_mask=bmask)
            probs = torch.sigmoid(logits)
            valid_mask = ~bmask
            all_probs.extend(probs[valid_mask].cpu().numpy())
            all_targets.extend(by[valid_mask].numpy())
    auc = roc_auc_score(all_targets, all_probs)
    auprc = average_precision_score(all_targets, all_probs)
    return auc, auprc

def train_model(train_loader, num_features, pos_weight_val, dev, epochs=10):
    model = TemporalTransformer(num_features=num_features).to(dev)
    criterion = nn.BCEWithLogitsLoss(pos_weight=pos_weight_val.to(dev))
    optimizer = torch.optim.AdamW(model.parameters(), lr=0.001, weight_decay=1e-4)

    model.train()
    for ep in range(1, epochs + 1):
        for bx, by, bmask in train_loader:
            bx, by, bmask = bx.to(dev), by.to(dev), bmask.to(dev)
            optimizer.zero_grad()
            logits = model(bx, src_key_padding_mask=bmask)
            valid_mask = ~bmask
            loss = criterion(logits[valid_mask], by[valid_mask])
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
            optimizer.step()
    return model

