# Advanced Feature Engineering: Deltas, Rolling Stats, and Continuous Elapsed Time (dt)
def add_advanced_clinical_features(df, id_c='patient_id'):
    df_proc = df.copy()
    key_vitals = ['HR', 'MAP', 'Resp', 'Temp', 'O2Sat', 'SBP', 'DBP']

    # 1. 3-Hour Rates of Change (Deltas)
    for col in key_vitals:
        if col in df_proc.columns:
            df_proc[f"{col}_delta3h"] = df_proc.groupby(id_c)[col].diff(periods=3).fillna(0.0)

    # 2. 6-Hour Rolling Aggregations (Min, Max, Mean)
    for col in ['HR', 'MAP', 'Resp', 'Temp']:
        if col in df_proc.columns:
            df_proc[f"{col}_min_6h"] = df_proc.groupby(id_c)[col].transform(lambda x: x.rolling(6, min_periods=1).min())
            df_proc[f"{col}_max_6h"] = df_proc.groupby(id_c)[col].transform(lambda x: x.rolling(6, min_periods=1).max())
            df_proc[f"{col}_mean_6h"] = df_proc.groupby(id_c)[col].transform(lambda x: x.rolling(6, min_periods=1).mean())

    # 3. Continuous Elapsed Time Since Last Measurement (delta_t in hours)
    ignore_cols = [id_c, target_col, 'SepsisLabel', 'sepsislabel', 'Unit1', 'Unit2', 'HospAdmTime', 'ICULOS']
    physio_cols = [c for c in df.columns if c not in ignore_cols]
    for col in physio_cols:
        is_nan = df_proc[col].isna()
        # Cumulative count of consecutive NaNs
        df_proc[f"{col}_elapsed_hrs"] = df_proc.groupby(id_c)[col].transform(
            lambda s: s.isna().astype(int).groupby((~s.isna()).cumsum()).cumsum()
        ).fillna(0.0)

    return df_proc

