class SepsisDataset(Dataset):
    def __init__(self, X, y, mask):
        self.X, self.y, self.mask = X, y, mask
    def __len__(self):
        return len(self.X)
    def __getitem__(self, idx):
        return self.X[idx], self.y[idx], self.mask[idx]

