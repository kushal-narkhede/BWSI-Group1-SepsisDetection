MAX_SEQ_LEN = 48

def build_3d_tensors(df, feature_cols, max_seq_len=48, id_c='patient_id', target_c='SepsisLabel'):
    grouped = df.groupby(id_c)
    num_patients = len(grouped)
    num_features = len(feature_cols)

    X_arr = np.zeros((num_patients, max_seq_len, num_features), dtype=np.float32)
    y_arr = np.zeros((num_patients, max_seq_len), dtype=np.float32)
    padding_mask = np.ones((num_patients, max_seq_len), dtype=bool)

    for idx, (_, group) in enumerate(grouped):
        seq_len = min(len(group), max_seq_len)
        X_arr[idx, :seq_len, :] = group[feature_cols].values[:seq_len]
        y_arr[idx, :seq_len] = group[target_c].values[:seq_len]
        padding_mask[idx, :seq_len] = False

    return (
        torch.tensor(X_arr, dtype=torch.float32),
        torch.tensor(y_arr, dtype=torch.float32),
        torch.tensor(padding_mask, dtype=torch.bool)
    )

