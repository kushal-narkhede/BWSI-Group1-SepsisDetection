def compute_integrated_gradients(model, X_tensor, mask_tensor, feature_names, device, steps=20):
    model.eval()
    sample_size = min(300, len(X_tensor))
    inputs = X_tensor[:sample_size].to(device)
    masks = mask_tensor[:sample_size].to(device)
    baseline = torch.zeros_like(inputs).to(device)

    scaled_inputs = [baseline + (float(i) / steps) * (inputs - baseline) for i in range(steps + 1)]
    grads = []

    for scaled_input in scaled_inputs:
        scaled_input.requires_grad = True
        logits = model(scaled_input, src_key_padding_mask=masks)
        valid_mask = ~masks
        valid_logits = logits[valid_mask]
        valid_logits.sum().backward()
        grads.append(scaled_input.grad.cpu().numpy())

    avg_grads = np.mean(grads, axis=0)
    integrated_grad = (inputs.cpu().numpy() - baseline.cpu().numpy()) * avg_grads

    valid_mask_3d = (~masks).cpu().numpy()[:, :, None]
    feature_importance = np.abs(integrated_grad * valid_mask_3d).mean(axis=(0, 1))

    return pd.Series(feature_importance, index=feature_names).sort_values(ascending=False)

