# Forward-fill physiological values and compute medians for unobserved start values
def add_missingness_and_impute(df, physio_cols, id_c, medians=None):
    df_proc = df.copy()

    # Binary missingness masks for base physiological variables
    base_cols = [c for c in physio_cols if not (c.endswith('_delta3h') or c.endswith('_min_6h') or c.endswith('_max_6h') or c.endswith('_mean_6h') or c.endswith('_elapsed_hrs'))]
    for col in base_cols:
        df_proc[f"{col}_is_missing"] = df_proc[col].isna().astype(np.float32)

    # Forward-fill missing observations
    df_proc[physio_cols] = df_proc.groupby(id_c)[physio_cols].ffill()

    # Apply baseline medians
    if medians is None:
        medians = df_proc[physio_cols].median()
    df_proc[physio_cols] = df_proc[physio_cols].fillna(medians)

    missing_cols = [f"{col}_is_missing" for col in base_cols]
    all_feature_cols = physio_cols + missing_cols
    return df_proc, all_feature_cols, medians

