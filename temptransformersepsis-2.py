def evaluate_metrics(model, loader, device):
    model.eval()
    all_probs, all_targets = [], []
    with torch.no_grad():
        for bx, by, bmask in loader:
            bx, by, bmask = bx.to(device), by.to(device), bmask.to(device)
            logits = model(bx, src_key_padding_mask=bmask)
            probs = torch.sigmoid(logits)
            valid_mask = ~bmask

            all_probs.extend(probs[valid_mask].cpu().numpy())
            all_targets.extend(by[valid_mask].cpu().numpy())

    all_probs = np.array(all_probs)
    all_targets = np.array(all_targets)

    auc = roc_auc_score(all_targets, all_probs)
    auprc = average_precision_score(all_targets, all_probs)
    brier = brier_score_loss(all_targets, all_probs)

    best_thresh = 0.5
    best_j = -1
    for thresh in np.linspace(0.1, 0.9, 81):
        preds = (all_probs >= thresh).astype(int)
        tn, fp, fn, tp = confusion_matrix(all_targets, preds, labels=[0, 1]).ravel()
        sens = tp / (tp + fn) if (tp + fn) > 0 else 0
        spec = tn / (tn + fp) if (tn + fp) > 0 else 0
        j_stat = sens + spec - 1
        if j_stat > best_j:
            best_j = j_stat
            best_thresh = thresh

    final_preds = (all_probs >= best_thresh).astype(int)
    tn, fp, fn, tp = confusion_matrix(all_targets, final_preds, labels=[0, 1]).ravel()
    sens = tp / (tp + fn) if (tp + fn) > 0 else 0
    spec = tn / (tn + fp) if (tn + fp) > 0 else 0
    f1 = f1_score(all_targets, final_preds)

    return {
        'AUROC': auc, 'AUPRC': auprc, 'Brier': brier,
        'Sensitivity': sens, 'Specificity': spec, 'F1': f1,
        'Optimal_Threshold': best_thresh
    }

